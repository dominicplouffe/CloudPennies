import type { Report, Snapshot } from './types';
import { BASIS_LABEL, shortService } from './catalog';
import { fmtDateLong, money, pct } from './util';

/** A shareable Markdown summary of the current report — paste into Slack, email or a ticket. */
export function reportMarkdown(snap: Snapshot, r: Report): string {
  const b = r.briefing;
  const L: string[] = [];
  L.push(`# CloudPennies briefing — ${snap.meta.accountLabel}`);
  L.push(`_Data through ${fmtDateLong(snap.meta.dataThrough)} · ${BASIS_LABEL[snap.meta.costBasis] ?? 'unblended'} cost, credits and refunds excluded_`);
  L.push('', `## ${b.headline}`, '', ...b.story.flatMap((p) => [p, '']));
  L.push('| | |', '|---|---|');
  L.push(`| Month to date | ${money(b.mtd)} |`);
  L.push(`| Projected month-end | ${money(b.projected)} |`);
  L.push(`| ${b.prevMonthLabel} total | ${money(b.prevMonthTotal)} |`);
  L.push(`| Savings identified | ${money(r.totalMonthlySavings)}/month |`);
  L.push(`| Effective savings rate | ${pct(r.commitments.esrPct, 1)} |`);
  L.push(`| Commitment coverage / utilization | ${pct(r.commitments.coveragePct)} / ${pct(r.commitments.utilizationPct)} |`);

  if (b.drivers.length) {
    L.push('', `## What changed (${b.compare.label} vs ${b.compare.prevLabel})`, '');
    for (const d of b.drivers) L.push(`- **${shortService(d.service)}** ${money(d.delta, { sign: true })} — ${d.why}`);
    for (const d of b.decreases) L.push(`- **${shortService(d.service)}** ${money(d.delta)} — ${d.why}`);
  }
  if (r.anomalies.length) {
    L.push('', '## Anomalies', '');
    for (const a of r.anomalies) L.push(`- **${a.title}**${a.ongoing ? ' _(ongoing)_' : ''} — ${a.summary}`);
  }
  if (r.commitments.expirations.length) {
    L.push('', '## Commitments coming up for renewal', '', '| Expires | Commitment | Discount at risk |', '|---|---|---|');
    for (const e of r.commitments.expirations) L.push(`| ${fmtDateLong(e.end)} (${e.daysLeft} days) | ${e.label} — ${e.detail} | ${money(e.monthlyExposure)}/month |`);
  }
  if (r.insights.length) {
    L.push('', '## Savings opportunities', '', '| Opportunity | Est. savings / month | Effort | Source |', '|---|---:|---|---|');
    for (const i of r.insights) L.push(`| ${i.urgent ? '⚑ ' : ''}${i.title} | ${i.monthlySavings > 0 ? money(i.monthlySavings) : '—'} | ${i.effort} | ${i.source} |`);
    L.push('', '### Details', '');
    for (const i of r.insights.slice(0, 15)) {
      L.push(`#### ${i.title}${i.monthlySavings > 0 ? ` — ${money(i.monthlySavings)}/month` : ''}`, '', i.summary, '');
      i.steps.forEach((s, k) => L.push(`${k + 1}. ${s}`));
      L.push('');
    }
  }
  L.push('', '_Generated by CloudPennies — every cloud dollar has a story._');
  return L.join('\n');
}
